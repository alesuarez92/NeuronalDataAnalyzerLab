  /* --------------------------- walkthrough ---------------------------- */
  var tourCount = 0;
  function buildTour(host) {
    var frames = TOURS[host.getAttribute("data-tour")];
    if (!frames) return;
    var id = "tour" + (++tourCount);
    var i = 0, timer = null;
    host.classList.add("tour");
    host.setAttribute("role", "region");
    host.setAttribute("aria-roledescription", "walkthrough");
    host.setAttribute("aria-label", host.getAttribute("data-label") || "Walkthrough");
    host.innerHTML =
      '<div class="stage">' +
        '<div class="frame"><img alt="" decoding="async"><span class="badge"></span></div>' +
        '<div class="bar" aria-hidden="true"><i></i></div>' +
        '<div class="controls">' +
          '<button type="button" class="ctl" data-act="prev" aria-label="Previous step">‹ Prev</button>' +
          '<button type="button" class="ctl primary" data-act="play" aria-pressed="false">Play</button>' +
          '<button type="button" class="ctl" data-act="next" aria-label="Next step">Next ›</button>' +
          '<a class="ctl" data-act="full" target="_blank" rel="noopener">Full size</a>' +
          '<span class="counter" aria-live="polite"></span>' +
        "</div>" +
      "</div>" +
      '<div class="side">' +
        '<div class="caption" aria-live="polite"><div class="win"></div><h3></h3><p class="txt"></p><p class="look"><b>Look for:</b> <span></span></p></div>' +
        '<ol aria-label="Steps"></ol>' +
      "</div>";
    var img = host.querySelector(".frame img"), badge = host.querySelector(".badge");
    var bar = host.querySelector(".bar i"), counter = host.querySelector(".counter");
    var win = host.querySelector(".win"), h = host.querySelector(".caption h3");
    var txt = host.querySelector(".txt"), look = host.querySelector(".look span");
    var full = host.querySelector('[data-act="full"]'), play = host.querySelector('[data-act="play"]');
    var list = host.querySelector("ol"), buttons = [], lastWin = null;
    frames.forEach(function (fr, k) {
      if (fr.w !== lastWin) { list.appendChild(el("li", { "class": "app" }, fr.w)); lastWin = fr.w; }
      var li = el("li"), b = el("button", { type: "button", id: id + "-s" + k },
        '<span class="n">' + (k + 1 < 10 ? "0" : "") + (k + 1) + "</span><span>" + fr.t + "</span>");
      b.addEventListener("click", function () { stop(); show(k); });
      li.appendChild(b); list.appendChild(li); buttons.push(b);
    });
    function src(k) { return "assets/frames/" + frames[k].f + ".png"; }
    function show(k) {
      i = (k + frames.length) % frames.length;
      var fr = frames[i];
      img.src = src(i);
      img.alt = fr.w + ": " + fr.t + ". " + fr.x;
      badge.textContent = DEMO + GEN[fr.g || "core"];
      full.href = src(i);
      win.textContent = fr.w;
      h.textContent = fr.t;
      txt.textContent = fr.x;
      look.textContent = fr.l;
      counter.textContent = (i + 1) + " / " + frames.length;
      bar.style.width = ((i + 1) / frames.length * 100) + "%";
      buttons.forEach(function (b, j) { if (j === i) b.setAttribute("aria-current", "step"); else b.removeAttribute("aria-current"); });
      var pre = new Image(); pre.src = src((i + 1) % frames.length);
    }
    function stop() {
      if (timer) { clearInterval(timer); timer = null; }
      play.textContent = "Play"; play.setAttribute("aria-pressed", "false");
    }
    function start() {
      stop();
      timer = setInterval(function () { show(i + 1); }, 6000);
      play.textContent = "Pause"; play.setAttribute("aria-pressed", "true");
    }
    host.querySelector('[data-act="prev"]').addEventListener("click", function () { stop(); show(i - 1); });
    host.querySelector('[data-act="next"]').addEventListener("click", function () { stop(); show(i + 1); });
    play.addEventListener("click", function () { if (timer) stop(); else start(); });
    if (reduceMotion) play.title = "Advances every 6 s. Your system asks for reduced motion, so it never starts on its own.";
    host.addEventListener("keydown", function (e) {
      if (e.target.tagName === "INPUT") return;
      if (e.key === "ArrowRight") { stop(); show(i + 1); e.preventDefault(); }
      else if (e.key === "ArrowLeft") { stop(); show(i - 1); e.preventDefault(); }
      else if (e.key === "Home") { stop(); show(0); e.preventDefault(); }
      else if (e.key === "End") { stop(); show(frames.length - 1); e.preventDefault(); }
    });
    host.tabIndex = 0;
    document.addEventListener("visibilitychange", function () { if (document.hidden) stop(); });
    show(0);
  }

